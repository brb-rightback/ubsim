#!/usr/bin/env python
"""Write a GENIE cross section spline file for an ExtGen tune.

Converts a table of an external generator's total cross sections into the
XML spline format that GENIE (and GENIEHelper's XSecTable) reads, with one
spline per (neutrino, current, target) for genie::ubext::ExtGenPXSec.

Input table: one point per line, '#' starts a comment,
    nu_pdg  current(CC|NC)  target_pdg  E[GeV]  sigma[1e-38 cm^2 per nucleus]
(the same format ExtGenPXSec reads through ExtGen-XSecTable).

Energy cap: points above --cap are dropped and replaced by zero knots up to
--extend-to. GENIE's GMCJDriver requires the spline range to extend beyond
the flux's maximum energy, so --extend-to must exceed the largest flux
energy (NuMI dk2nu files reach O(100) GeV).

Works with python 2.7 (uboonecode v08 environment) and python 3.
"""
from __future__ import print_function

import argparse
import collections
import sys

# GENIE natural units: Units.h defines meter = 5.07e15/GeV, so
# 1 cm^2 = (5.07e13)^2 GeV^-2. Use exactly GENIE's value.
CM2_IN_GENIE_UNITS = (5.07e13) ** 2
XSEC_UNIT = 1e-38 * CM2_IN_GENIE_UNITS  # 1e-38 cm^2 in GENIE units

ALG = "genie::ubext::ExtGenPXSec/Default"
FREE_PROTON = 1000010010
FREE_NEUTRON = 1000000010


def read_table(path):
    tables = collections.defaultdict(list)
    with open(path) as f:
        for lineno, line in enumerate(f, 1):
            line = line.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) != 5 or line[1] not in ("CC", "NC"):
                sys.exit("%s:%d: expected 'nu_pdg CC|NC target_pdg E sigma'" % (path, lineno))
            nu, cur, tgt = int(line[0]), line[1], int(line[2])
            E, sigma = float(line[3]), float(line[4])
            if E <= 0 or sigma < 0:
                sys.exit("%s:%d: E must be > 0 and sigma >= 0" % (path, lineno))
            tables[(nu, cur, tgt)].append((E, sigma))
    for key, pts in tables.items():
        pts.sort()
        energies = [e for e, _ in pts]
        if len(set(energies)) != len(energies):
            sys.exit("duplicate energies in table for %s" % (key,))
    return tables


def spline_key(nu, cur, tgt):
    # Must match XSecSplineList::BuildSplineKey + Interaction::AsString for the
    # interactions made by ExtGenInteractionListGenerator (scattering type
    # kScNull prints as "Unknown"; free nucleons have the struck nucleon set).
    hitnuc = ""
    if tgt == FREE_PROTON:
        hitnuc = "N:2212;"
    elif tgt == FREE_NEUTRON:
        hitnuc = "N:2112;"
    return "%s/nu:%d;tgt:%d;%sproc:Weak[%s],Unknown;" % (ALG, nu, tgt, hitnuc, cur)


def knots(pts, cap, extend_to):
    out = [(e, s) for e, s in pts if e <= cap]
    if not out:
        return out
    last_e = out[-1][0]
    if extend_to > last_e:
        # Zero knots just above the last point and at the end of the range:
        # GENIE interpolates linearly to a zero knot and returns 0 between
        # two zero knots.
        step = min(1e-3, 0.5 * (extend_to - last_e))
        out.append((last_e + step, 0.0))
        out.append((extend_to, 0.0))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("table", help="input cross section table")
    ap.add_argument("output", help="output GENIE spline XML file")
    ap.add_argument("--tune", required=True, help="GENIE tune name, e.g. GB25_05a_00_000")
    ap.add_argument("--cap", type=float, default=8.0,
                    help="energy cap [GeV]: sigma = 0 above this (default 8)")
    ap.add_argument("--extend-to", type=float, default=200.0,
                    help="last (zero) knot [GeV], must exceed the flux max energy (default 200)")
    args = ap.parse_args()

    tables = read_table(args.table)
    if not tables:
        sys.exit("no cross sections found in " + args.table)

    with open(args.output, "w") as out:
        out.write('<?xml version="1.0" encoding="ISO-8859-1"?>\n\n')
        out.write("<!-- generated by ubsim/ExtGen/tools/extgen_make_splines.py\n")
        out.write("     from %s (cap %g GeV, zero knots up to %g GeV) -->\n\n"
                  % (args.table, args.cap, args.extend_to))
        out.write('<genie_xsec_spline_list version="3.00" uselog="0">\n\n')
        out.write('  <genie_tune name="%s">\n\n' % args.tune)
        for key in sorted(tables):
            ks = knots(tables[key], args.cap, args.extend_to)
            if len(ks) < 2:
                sys.exit("fewer than 2 knots below the cap for %s" % (key,))
            out.write('    <spline name="%s" nknots="%d">\n' % (spline_key(*key), len(ks)))
            for e, s in ks:
                out.write("\t<knot> <E> %10.5f </E> <xsec> %.10e </xsec> </knot>\n"
                          % (e, s * XSEC_UNIT))
            out.write("    </spline>\n")
        out.write("  </genie_tune>\n")
        out.write("</genie_xsec_spline_list>\n")

    print("Wrote %d splines for tune %s to %s" % (len(tables), args.tune, args.output))


if __name__ == "__main__":
    main()
